function calcularPresupuesto() {                                      
                                                                      
                                                                      
    const formulario = document.querySelector("form");                
    const campos = formulario.querySelectorAll("input");              
                                                                      
                                                                      
    const numeroInvitados = Number(campos[0].value);                  
    const costoComida = Number(campos[1].value);                      
    const costoBebida = Number(campos[2].value);                      
    const costoDecoracion = Number(campos[3].value);                  
    const costoMusica = Number(campos[4].value);                      
    const porcentajePropina = Number(campos[5].value);                
                                                                      
                                                                      
    // Validar campos vacíos                                          
    const hayCamposVacios = Array.from(campos).some(                  
        campo => campo.value.trim() === ""                            
    );                                                                
                                                                      
                                                                      
    if (hayCamposVacios) {                                            
        alert("Completa todos los campos.");                          
        return;                                                       
    }                                                                 
                                                                      
                                                                      
    // Validar valores                                                
    const valores = [                                                 
        numeroInvitados,                                              
        costoComida,                                                  
        costoBebida,                                                  
        costoDecoracion,                                              
        costoMusica,                                                  
        porcentajePropina                                             
    ];                                                                
                                                                      
                                                                      
    if (valores.some(valor => !Number.isFinite(valor) || valor < 0)) {
        alert("Ingresa valores válidos y no negativos.");             
        return;                                                       
    }                                                                 
                                                                      
                                                                      
    if (numeroInvitados <= 0) {                                       
        alert("El número de invitados debe ser mayor que cero.");     
        return;                                                       
    }                                                                 
                                                                      
                                                                      
    // Realizar cálculos                                              
    const comidaTotal = numeroInvitados * costoComida;                
    const bebidaTotal = numeroInvitados * costoBebida;                
                                                                      
                                                                      
    const subtotal =                                                  
        comidaTotal +                                                 
        bebidaTotal +                                                 
        costoDecoracion +                                             
        costoMusica;                                                  
                                                                      
                                                                      
    const propina = subtotal * (porcentajePropina / 100);             
    const totalGeneral = subtotal + propina;                          
    const costoPorInvitado = totalGeneral / numeroInvitados;          
                                                                      
                                                                      
    // Formato de moneda colombiana                                   
    const formatoMoneda = valor =>                                    
        valor.toLocaleString("es-CO", {                               
            style: "currency",                                        
            currency: "COP",                                          
            minimumFractionDigits: 2,                                 
            maximumFractionDigits: 2                                  
        });                                                           
                                                                      
                                                                      
    // Recorrer las filas de la tabla                                 
    const filas = document.querySelectorAll("table tbody tr");        
                                                                      
                                                                      
    const resultados = [                                              
        comidaTotal,                                                  
        bebidaTotal,                                                  
        costoDecoracion,                                              
        costoMusica,                                                  
        subtotal,                                                     
        propina,                                                      
        totalGeneral,                                                 
        costoPorInvitado                                              
    ];                                                                
                                                                      
                                                                      
    filas.forEach((fila, indice) => {                                 
        const celdas = fila.querySelectorAll("td");                   
                                                                      
                                                                      
        if (celdas.length >= 2) {                                     
            celdas[1].textContent =                                   
                formatoMoneda(resultados[indice]);                    
        }                                                             
    });                                                               
                                                                      
                                                                      
    alert("¡Presupuesto calculado correctamente!");                   
}                                                                     































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































    
    
    
    


    
    
    
    


    
    
    
    


    
    
    
    
    
    
    
    
    


    






    


















    













    


































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































